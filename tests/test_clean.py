#!/usr/bin/env python3
"""Cleaner tests: the rolling-caption artifact is the thing most likely to silently corrupt the corpus."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import pipeline

FAIL = []

def check(name, cond, detail=""):
    print(("  PASS  " if cond else "  FAIL  ") + name + ("" if cond else f"  -> {detail}"))
    if not cond:
        FAIL.append(name)

here = os.path.dirname(os.path.abspath(__file__))
vtt = open(os.path.join(here, "sample_auto.vtt"), encoding="utf-8").read()

words = pipeline.dedupe_rolling(pipeline.parse_subtitle_lines(vtt))
text = " ".join(words)
print("cleaned:", text)

check("no repeated 'first thing i look at'", text.count("first thing i look at") == 1, text)
check("no repeated 'customer concentration'", text.count("customer concentration") == 1, text)
check("no repeated 'thirty percent'", text.count("thirty percent") == 1, text)
check("keeps final non-overlapping cue", "two and a half times SDE" in text, text)
check("drops [Music] noise", "music" not in text.lower(), text)
check("no timestamps leak", "-->" not in text and "00:00" not in text, text)
check("no cue tags leak", "<" not in text and "align:" not in text, text)
check("content order preserved",
      text.index("janitorial") < text.index("thirty percent") < text.index("SDE"), text)

# exact expected reconstruction
expected = ("so the first thing i look at on a janitorial deal is the customer concentration "
            "if one client is more than thirty percent of revenue that multiple comes down "
            "we paid two and a half times SDE for it")
check("exact reconstruction", text == expected, f"\n  got:      {text}\n  expected: {expected}")

# inbox (MCP plain-text) path
inbox_sample = """# Transcript: Test Video

Source video: https://www.youtube.com/watch?v=abc12345678
Language: en - Duration: 1:00 - Words: 20

## Transcript
[0:01] we charge fourteen cents a square foot
[0:05] we charge fourteen cents a square foot on that contract
[0:09] and labour runs about fifty two percent
---
Generated by https://youtube-transcript.ai - free YouTube transcript & summary extractor.
"""
paras = pipeline.parse_inbox_text(inbox_sample)
itext = " ".join(paras)
print("inbox cleaned:", itext)
check("inbox strips header", "Source video" not in itext, itext)
check("inbox strips footer", "Generated by" not in itext, itext)
check("inbox strips timestamps", "[0:" not in itext, itext)
check("inbox dedupes rolling", itext.count("fourteen cents") == 1, itext)
check("inbox keeps tail", "fifty two percent" in itext, itext)

# helpers
check("safe_title slug", pipeline.safe_title("How to Bid a Contract?! (2024)") == "How-to-Bid-a-Contract-2024",
      pipeline.safe_title("How to Bid a Contract?! (2024)"))
check("hms", pipeline.hms(3725) == "1:02:05" and pipeline.hms(95) == "1:35", pipeline.hms(3725))
check("keyword include/exclude",
      pipeline.matches_keywords("Cleaning business tips", ["cleaning"], ["course"]) and
      not pipeline.matches_keywords("My cleaning course", ["cleaning"], ["course"]))

# filters
ok, why = pipeline.keep_video({"title": "Short one", "duration": 120}, {"tier": 2, "min_duration": 480})
check("rejects short video", not ok, why)
ok, why = pipeline.keep_video({"title": "Real talk on janitorial", "duration": 1800}, {"tier": 2, "min_duration": 480})
check("keeps long video", ok, why)
ok, why = pipeline.keep_video({"title": "Free webinar replay", "duration": 1800}, {"tier": 2, "min_duration": 480})
check("rejects promo", not ok, why)

print()
print(("ALL TESTS PASSED" if not FAIL else f"{len(FAIL)} FAILED: {FAIL}"))
sys.exit(1 if FAIL else 0)
